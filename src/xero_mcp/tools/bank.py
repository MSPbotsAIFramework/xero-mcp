"""Bank transactions (spend/receive money, with their reconciled status) and bank transfers.

PRD-21293. Not covered: automated statement-line matching (Xero's "Reconcile" screen) and
bank feed import — both need the separate Bank Feeds partner API, a different integration
shape than the Accounting API this server already uses exclusively.
"""

from typing import Annotated, Any, Literal

from mcp.server.fastmcp import FastMCP
from pydantic import Field

from ..api_client import XeroClient
from ._common import (
    READ_ONLY,
    WRITES,
    ClientFactory,
    IsoDate,
    Offset,
    Page,
    compact,
    first,
    guid,
    literal,
    locate,
    page_result,
    run_tool,
    write_result,
)
from .invoices import LineItem

# The four Xero-internal variants (*-OVERPAYMENT, *-PREPAYMENT) are generated by Xero itself as
# a side effect of other actions; listing can filter by them, but xero_bank_transactions_create
# only ever writes the two a person would ask for in plain language.
BankTransactionType = Literal[
    "SPEND", "RECEIVE", "SPEND-OVERPAYMENT", "RECEIVE-OVERPAYMENT", "SPEND-PREPAYMENT", "RECEIVE-PREPAYMENT"
]
CreatableBankTransactionType = Literal["SPEND", "RECEIVE"]


def register(mcp: FastMCP, client_factory: ClientFactory) -> None:
    @mcp.tool(annotations=READ_ONLY)
    async def xero_bank_transactions_list(
        page: Page = None,
        BankAccountID: Annotated[str | None, Field(description="Only transactions on this bank account (UUID).")] = None,
        Type: Annotated[BankTransactionType | None, Field(description="Only transactions of this type.")] = None,
        Status: Annotated[Literal["AUTHORISED", "DELETED"] | None, Field(description="Only transactions in this status.")] = None,
        offset: Offset = None,
    ) -> str:
        """List bank spend/receive transactions, newest first, 100 per page.

        Each record shows date, type, amount, reference, bank account and whether it is reconciled.
        """

        async def action(client: XeroClient) -> dict:
            number, start = locate(offset, page)
            clauses = [
                f'BankAccount.AccountID==Guid("{guid(BankAccountID, "BankAccountID")}")' if BankAccountID else None,
                f"Type=={literal(Type)}" if Type else None,
                f"Status=={literal(Status)}" if Status else None,
            ]
            params = compact(
                {"page": number, "where": " AND ".join(c for c in clauses if c) or None, "order": "Date DESC"}
            )
            return page_result("BankTransactions", await client.get("BankTransactions", params), number, start)

        return await run_tool("xero_bank_transactions_list", client_factory, action)

    @mcp.tool(annotations=READ_ONLY)
    async def xero_bank_transactions_get(
        bankTransactionId: Annotated[str, Field(description="Bank transaction id (UUID).")],
    ) -> str:
        """Get one bank transaction in full: line items, tax, totals and whether it is reconciled."""

        async def action(client: XeroClient) -> Any:
            return first(
                await client.get(f"BankTransactions/{guid(bankTransactionId, 'bankTransactionId')}"), "BankTransactions"
            )

        return await run_tool("xero_bank_transactions_get", client_factory, action)

    @mcp.tool(annotations=WRITES)
    async def xero_bank_transactions_create(
        Type: Annotated[CreatableBankTransactionType, Field(description="SPEND = money out, RECEIVE = money in.")],
        BankAccountID: Annotated[str, Field(description="Bank account id (UUID) the money moved through.")],
        LineItems: Annotated[list[LineItem], Field(description="At least one line.", min_length=1)],
        Date: IsoDate,
        ContactID: Annotated[str | None, Field(description="Contact id (UUID); Xero allows a transaction with none.")] = None,
        Reference: Annotated[str | None, Field(description="Reference.")] = None,
    ) -> str:
        """Record money spent from or received into a bank account, not tied to an invoice/bill payment.

        Only when the user explicitly asks.
        """

        async def action(client: XeroClient) -> Any:
            transaction = compact(
                {
                    "Type": Type,
                    "BankAccount": {"AccountID": guid(BankAccountID, "BankAccountID")},
                    "LineItems": [item.model_dump(exclude_none=True) for item in LineItems],
                    "Contact": {"ContactID": guid(ContactID, "ContactID")} if ContactID else None,
                    "Date": Date,
                    "Reference": Reference or None,
                }
            )
            return write_result(await client.put("BankTransactions", {"BankTransactions": [transaction]}), "BankTransactions")

        return await run_tool("xero_bank_transactions_create", client_factory, action)

    @mcp.tool(annotations=READ_ONLY)
    async def xero_bank_transfers_list(page: Page = None, offset: Offset = None) -> str:
        """List transfers between bank accounts, newest first, 100 per page.

        Each record shows the source and destination account, amount and date.
        """

        async def action(client: XeroClient) -> dict:
            # BankTransfers has no where/order support in Xero's API; newest-first is the default.
            number, start = locate(offset, page)
            return page_result("BankTransfers", await client.get("BankTransfers", compact({"page": number})), number, start)

        return await run_tool("xero_bank_transfers_list", client_factory, action)

    @mcp.tool(annotations=READ_ONLY)
    async def xero_bank_transfers_get(
        bankTransferId: Annotated[str, Field(description="Bank transfer id (UUID).")],
    ) -> str:
        """Get one transfer in full: both bank accounts, amount, date and the two linked bank transaction ids."""

        async def action(client: XeroClient) -> Any:
            return first(await client.get(f"BankTransfers/{guid(bankTransferId, 'bankTransferId')}"), "BankTransfers")

        return await run_tool("xero_bank_transfers_get", client_factory, action)

    @mcp.tool(annotations=WRITES)
    async def xero_bank_transfers_create(
        FromBankAccountID: Annotated[str, Field(description="Source bank account id (UUID).")],
        ToBankAccountID: Annotated[str, Field(description="Destination bank account id (UUID).")],
        Amount: Annotated[float, Field(description="Amount to transfer.", gt=0)],
        Date: IsoDate,
    ) -> str:
        """Transfer funds between two of the organisation's bank accounts. Only when the user explicitly asks."""

        async def action(client: XeroClient) -> Any:
            transfer = {
                "FromBankAccount": {"AccountID": guid(FromBankAccountID, "FromBankAccountID")},
                "ToBankAccount": {"AccountID": guid(ToBankAccountID, "ToBankAccountID")},
                "Amount": Amount,
                "Date": Date,
            }
            return write_result(await client.put("BankTransfers", {"BankTransfers": [transfer]}), "BankTransfers")

        return await run_tool("xero_bank_transfers_create", client_factory, action)
